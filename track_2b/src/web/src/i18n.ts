const STRINGS: Record<Lang, Dict> = { en, de, zh };

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): Translate {
  const dict = STRINGS[lang];
  return (key, vars) => {
    const s = dict[key] ?? en[key];
    return vars ? s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : s;
  };
}

/** Locale for number formatting: Swiss conventions in EN and DE. */
export const NUMBER_LOCALE: Record<Lang, string> = { en: "en-CH", de: "de-CH", zh: "zh-CN" };

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

export const I18nContext = createContext<I18n>({ lang: "en", setLang: () => undefined, t: makeT("en") });

