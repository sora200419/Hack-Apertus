"""Render data/eval/results/results.md from summary.json (tables for technical_report.md, section 5)."""

from __future__ import annotations

from .util import md_table, pct

SYSTEM_LABELS = {
    "bm25": "Baseline: BM25 top-1",
    "tfidf": "Baseline: char n-gram TF-IDF top-1",
    "fused": "Baseline: fused retrieval (RRF) top-1",
    "retrieval_only": "Ours, no model: retrieval + margin rule (abstains)",
    "llm_small": "Ours: Apertus small rewrite + small rerank",
    "llm_large": "Ours: Apertus small rewrite + large rerank",
}
SUBSET_LABELS = {
    "main": "Hand-labelled BOM lines and finished goods (EN/DE/FR/IT)",
    "hscodecomp": "HSCodeComp e-commerce titles (EN), chapters 39/40/70/73/74/76/84/85/90/91",
    "parallel": "Parallel subset (same concepts in EN/DE/FR/IT)",
}


def render(summary: dict) -> str:
    g = summary["generated_with"]
    parts = [
        "# OriginPass CH-CN: evaluation results",
        "Generated by `python -m eval.run_all` from `data/eval/results/summary.json`. "
        f"LLM mode `{g['mode']}`, large model `{g['llm_name']}`, small model `{g['llm_name_small']}`, "
        f"rule pack `{g['rulepack']}` (sha256 {g['rulepack_sha256'][:12]}), gold file sha256 "
        f"{g['gold_sha256'][:12]}, replay cache entries {g['replay_cache_entries']}, commit `{g['commit'] or 'n/a'}`.",
        "A model system marked *not run* had no live endpoint and no replay-cache entry; it is reported, "
        "never silently replaced by the retrieval fallback.",
        _headline(summary),
        _e1(summary["e1"]),
        _e2(summary["e2"]),
        _e3(summary["e3"]),
        _e4(summary["e4"]),
    ]
    return "\n\n".join(parts) + "\n"


def _status_or(system: dict, value: str) -> str:
    return value if system["status"] == "run" else f"{system['status']}: {system.get('note', '')}".strip()


def _headline(s: dict) -> str:
    e1, e2, e3, e4 = s["e1"], s["e2"], s["e3"], s["e4"]
    main = e1["subsets"]["main"]
    rows: list[list[object]] = []
    for name in ("bm25", "fused"):
        m = main[name]
        rows.append([SYSTEM_LABELS[name], f"HS6 top-1 accuracy, BOM test set (n={m['n']})", pct(m["top1_hs6"])])
    ro = main["retrieval_only"]
    rows.append(
        [
            SYSTEM_LABELS["retrieval_only"],
            f"coverage / selective HS6 accuracy (n={ro['n']})",
            f"{pct(ro['coverage'])} / {pct(ro['selective_hs6'])}",
        ]
    )
    for name in ("llm_small", "llm_large"):
        m, st = main[name], e1["systems"][name]
        rows.append([SYSTEM_LABELS[name], f"HS6 top-1 accuracy (n={m['n']})", _status_or(st, pct(m["top1_hs6"]))])
    base = e2["llm_baseline"]
    rows.append(
        [
            "Baseline: LLM-only origin verdict (Apertus large, rule text EN+ZH in the prompt)",
            f"accuracy / false-PASS rate vs engine (n={base['items']})",
            _status_or(base, f"{pct(base.get('accuracy'))} / {pct(base.get('false_pass_rate'))}"),
        ]
    )
    rnd = e2["sweep"]["all"] if "sweep" in e2 else e2["synthetic"]["random"]
    rows.append(
        [
            "Ours: deterministic engine vs independent reference",
            f"status agreement / false-PASS rate (N={rnd['n']} synthetic BOMs)",
            f"{pct(rnd['status_agreement'])} / {pct(rnd['false_pass_rate'])}",
        ]
    )
    rows.append(
        [
            "Ours: dossier for the 5 demos",
            "fact checks passed / model-written texts / template fallbacks",
            f"{pct(e3['fact_check_pass_rate'])} / {e3['model_written']} of {e3['model_texts']}"
            f" / {e3['template_fallbacks']}",
        ]
    )
    proj = e4["projection"]["chf_per_1000_bom_lines"]
    rows.append(
        [
            "Projection: HS suggestion cost",
            "CHF per 1,000 BOM lines, 8B only / 70B only",
            f"{_chf(proj['8b_only'])} / {_chf(proj['70b_only'])}",
        ]
    )
    return "## Headline\n\n" + md_table(["Setup", "Metric", "Result"], rows)


def _chf(x: float | None) -> str:
    return "n/a" if x is None else f"CHF {x:.4f}" if x < 1 else f"CHF {x:.2f}"


def _e1(e1: dict) -> str:
    out = ["## E1: HS classification (test split)"]
    counts = e1["gold"]["counts"]
    out.append(
        "Gold set `data/eval/hs_gold.jsonl`: "
        + ", ".join(f"{k} {sum(v.values())}" for k, v in counts.items())
        + ". Top-1 counts an abstention as wrong; selective accuracy is measured on the non-abstained items; "
        "top-3 of a classifier is its choice followed by the retrieval candidates it shows; recall@10 is the "
        "share of items whose gold code is among the 10 candidates (the reranker's ceiling)."
    )
    header = [
        "System",
        "n",
        "Top-1 HS6 [95% CI]",
        "Top-1 HS4",
        "Top-3 HS6",
        "Top-3 HS4",
        "Recall@10",
        "Coverage",
        "Selective HS6",
    ]
    for subset, label in SUBSET_LABELS.items():
        rows: list[list[object]] = []
        for name, label_sys in SYSTEM_LABELS.items():
            m, st = e1["subsets"][subset][name], e1["systems"][name]
            if st["status"] == "not run":
                rows.append([label_sys, *(["not run"] * (len(header) - 1))])
                continue
            ci = m["top1_hs6_ci95"]
            ci_txt = f" [{pct(ci[0])}, {pct(ci[1])}]" if ci else ""
            rows.append(
                [
                    label_sys + ("" if st["status"] == "run" else f" ({st['status']})"),
                    m["n"],
                    pct(m["top1_hs6"]) + ci_txt,
                    pct(m["top1_hs4"]),
                    pct(m["top3_hs6"]),
                    pct(m["top3_hs4"]),
                    pct(m["recall_at_10"]),
                    pct(m["coverage"]),
                    pct(m["selective_hs6"]),
                ]
            )
        out.append(f"### {label}\n\n" + md_table(header, rows))
    notes = [f"- {SYSTEM_LABELS[n]}: {st['note']}" for n, st in e1["systems"].items() if st.get("note")]
    if notes:
        out.append("\n".join(notes))

    langs = ("en", "de", "fr", "it")
    rows = []
    for name, label in SYSTEM_LABELS.items():
        per = e1["per_language"]["main"][name]
        cells = [
            f"{pct(per[lg]['top1_hs6'])} (n={per[lg]['n']})" if lg in per and per[lg]["n"] else "not run"
            for lg in langs
        ]
        rows.append([label, *cells])
    out.append(
        "### Top-1 HS6 accuracy by language (hand-labelled BOM test set)\n\n" + md_table(["System", *langs], rows)
    )

    rows = []
    for name, label in SYSTEM_LABELS.items():
        x = e1["cross_lingual"][name]
        if not x["concepts"]:
            rows.append([label, 0, "not run", "not run", "not run", "not run"])
            continue
        vs = x["agree_with_en"]
        rows.append(
            [
                label,
                x["concepts"],
                pct(x["all_languages_agree"]),
                pct(vs.get("de")),
                pct(vs.get("fr")),
                pct(vs.get("it")),
            ]
        )
    out.append(
        "### Cross-lingual consistency (parallel test concepts; same non-abstained top-1 code)\n\n"
        + md_table(["System", "Concepts", "All 4 agree", "DE = EN", "FR = EN", "IT = EN"], rows)
    )

    rows = [
        [ex["text"], ex["lang"], ex["gold"], *[ex[name] or "abstain" for name in SYSTEM_LABELS]]
        for ex in e1["examples"]
    ]
    out.append(
        "### Examples (first non-English BOM test items)\n\n"
        + md_table(["Text", "Lang", "Gold", "BM25", "TF-IDF", "Fused", "Retrieval-only", "Small", "Large"], rows)
    )
    return "\n\n".join(out)


def _e2(e2: dict) -> str:
    syn = e2["synthetic"]
    cfg = syn["config"]
    out = [
        "## E2: origin verdicts",
        f"Engine vs the independent reference implementation (`eval/reference.py`) on seeded synthetic BOMs "
        f"(seed {cfg['seed']}, chapters {', '.join(cfg['chapters'])}): {cfg['n_random']} random BOMs plus boundary "
        f"cases for up to {cfg['rules_per_chapter']} rules per chapter.",
    ]
    rows: list[list[object]] = []
    sweep = e2.get("sweep")
    blocks = [(name, syn[name]) for name in ("random", "edge")]
    if sweep:
        blocks.append((f"all-chapter sweep ({sweep['config']['chapters']} chapters)", sweep["all"]))
    for name, a in blocks:
        rows.append(
            [
                name,
                a["n"],
                pct(a["status_agreement"]),
                pct(a["full_agreement"]),
                a["false_pass"],
                pct(a["false_pass_rate"]),
                a["false_fail"],
                ", ".join(f"{k} {v}" for k, v in sorted(a["reference_status_counts"].items())),
            ]
        )
    out.append(
        md_table(
            [
                "Cases",
                "n",
                "Status agreement",
                "Full agreement",
                "False PASS",
                "False-PASS rate",
                "False FAIL",
                "Reference labels",
            ],
            rows,
        )
    )
    conf = syn["random"]["confusion_reference_x_engine"]
    out.append(
        "Confusion matrix, random cases (rows: reference, columns: engine)\n\n"
        + md_table(["Reference \\ Engine", *conf], [[r, *conf[r].values()] for r in conf])
    )
    sweep_disagreements = e2.get("sweep", {}).get("disagreements", [])
    if sweep_disagreements:
        out.append(f"All-chapter sweep: {len(sweep_disagreements)} disagreement(s); see summary.json.")
    if syn["disagreements"]:
        out.append(
            "Disagreements (first ones):\n\n"
            + md_table(
                ["Case", "Kind", "Fields", "Reference", "Engine"],
                [
                    [d["case_id"], d["kind"], ", ".join(d["fields"]), d["reference"], d["engine"]]
                    for d in syn["disagreements"]
                ],
            )
        )

    demo_rows = [
        [
            r["product_id"],
            r["hs6"],
            r["rule_id"],
            f"{r['nom_pct']}%",
            r["threshold_pct"],
            r["reference_status"],
            r["engine_status"],
        ]
        for r in e2["demos"]["table"]
    ]
    out.append(
        "### Demo products\n\n"
        + md_table(["Product", "HS6", "Rule", "Non-originating share", "VNM limit %", "Reference", "Engine"], demo_rows)
    )
    if e2["demos"]["swaps"]:
        out.append(
            md_table(
                ["Product", "Single supplier swap", "Before", "After"],
                [[s["product_id"], s["swap"], s["before"], s["after"]] for s in e2["demos"]["swaps"]],
            )
        )

    b = e2["llm_baseline"]
    sample = b["sample"]
    if b["status"] == "not run":
        result = [["LLM-only (Apertus large)", "all", f"not run: {b.get('note', '')}"]]
    else:
        result = [
            ["LLM-only (Apertus large)", "status accuracy vs engine", pct(b["accuracy"])],
            ["LLM-only (Apertus large)", "false-PASS rate", f"{pct(b['false_pass_rate'])} ({b['false_pass']} cases)"],
            [
                "LLM-only (Apertus large)",
                "VNM % mean absolute error",
                f"{b['nom_pct_mae_pp']} pp (n={b['nom_pct_answers']})",
            ],
            ["LLM-only (Apertus large)", "unparseable replies", b["unparseable"]],
        ]
    result.append(
        [
            "Ours: deterministic engine",
            "status accuracy / false PASS",
            "reference for this comparison (100% / 0 by definition)",
        ]
    )
    out.append(
        f"### LLM-only baseline ({sample['synthetic']} synthetic + {sample['demos']} demo BOMs; "
        "same inputs as the engine)\n\n" + md_table(["Setup", "Metric", "Result"], result)
    )
    return "\n\n".join(out)


def _text_cell(t: dict) -> str:
    return f"{t['llm_source']}, {t['attempts']} att., {t['checks_passed']}/{t['checks_total']} checks"


def _e3(e3: dict) -> str:
    rows = [
        [
            d["product_id"],
            d["status"],
            *[
                _text_cell(d["texts"][n])
                for n in ("explanation_en", "explanation_de", "letter_zh", "back_translation_en")
            ],
            "yes" if d["letter_glossary_ok"] else "missing " + ", ".join(d["letter_glossary_missing"]),
        ]
        for d in e3["demos"]
    ]
    summary = (
        f"Fact checks passed: {pct(e3['fact_check_pass_rate'])}; texts with all checks passed: "
        f"{pct(e3['texts_all_checks_passed'])}; letter glossary compliance: {pct(e3['letter_glossary_compliance'])}; "
        f"model-written texts {e3['model_written']} of {e3['model_texts']}, "
        f"template fallbacks {e3['template_fallbacks']}, generation attempts {e3['attempts_total']}. "
        f"Native-speaker rating sheet: `{e3.get('rating_sheet', 'not written')}`."
    )
    return "\n\n".join(
        [
            "## E3: export dossier",
            md_table(
                [
                    "Product",
                    "Verdict",
                    "Explanation EN",
                    "Explanation DE",
                    "Letter ZH",
                    "Back-translation EN",
                    "ZH glossary",
                ],
                rows,
            ),
            summary,
        ]
    )


def _e4(e4: dict) -> str:
    m = e4["measured"]
    by_model = m["cost_log"]["by_model"]
    out = ["## E4: cost and latency"]
    if by_model:
        rows = [
            [
                model,
                v["calls"],
                v["prompt_tokens"],
                v["completion_tokens"],
                f"{v['cost_chf']:.4f}",
                v["latency_p50_s"],
                v["latency_p95_s"],
            ]
            for model, v in sorted(by_model.items())
        ]
        out.append(
            "Measured (answered calls in this run, live or replayed with their recorded tokens and latency)\n\n"
            + md_table(
                ["Model", "Calls", "Prompt tokens", "Completion tokens", "CHF", "p50 latency s", "p95 latency s"], rows
            )
        )
    else:
        out.append("Measured: no model call was answered in this run, so there is no measured cost or latency.")
    rows = [
        [
            name,
            x["calls_attempted"],
            x["calls_answered"],
            f"{x['cost_chf']:.4f}",
            x["units_answered"],
            x["chf_per_unit"] if x["chf_per_unit"] is not None else "n/a",
        ]
        for name, x in m["per_experiment"].items()
    ]
    out.append(
        md_table(["Experiment", "Calls attempted", "Calls answered", "CHF", "Units answered", "CHF per unit"], rows)
    )

    p = e4["projection"]
    a = p["assumptions"]
    rows = [
        [label, _chf(p[key]["8b_only"]), _chf(p[key]["70b_only"]), _chf(p[key]["code_roles"])]
        for label, key in (
            ("1,000 BOM lines (rewrite + rerank)", "chf_per_1000_bom_lines"),
            ("1,000 dossiers (3 texts, 1 attempt)", "chf_per_1000_dossiers"),
        )
    ]
    out.append(
        f"**{p['label']}.** Prices (USD per 1M tokens, input/output): {a['prices_usd_per_m_tokens']}, "
        f"USD->CHF {a['usd_to_chf']}. Unmeasured prompts: {a['chars_per_token']} Latin characters or "
        f"{a['cjk_chars_per_token']} CJK character per token; "
        f"unmeasured completions: {a['completion_tokens_if_unmeasured']}.\n\n"
        + md_table(["Projected cost per", "Apertus 8B only", "Apertus 70B only", "Roles used by the code"], rows)
    )
    rows = [[tag, x["basis"], x["prompt_tokens"], x["completion_tokens"]] for tag, x in p["token_profiles"].items()]
    out.append(md_table(["Call type", "Token basis", "Prompt tokens", "Completion tokens"], rows))
    return "\n\n".join(out)
